import { useMemo, useState } from 'react'
import { api } from '../api'
import { useAsync } from '../lib/hooks'
import { Card, EmptyState, ErrorState, Field, Notice, PageHeader, Skeleton } from '../components/ui'
import { RunLink, VerdictBadge } from '../components/common'
import { downloadBlob, exportFileName } from '../lib/download'
import { formatDateTime } from '../lib/format'

const FORMATS = [
  { format: 'md', label: 'Markdown report' },
  { format: 'html', label: 'HTML report' },
  { format: 'csv', label: 'CSV results' },
  { format: 'json', label: 'JSON results' },
  { format: 'ci', label: 'CI summary (JSON)' },
]

export default function ReportsPage() {
  const runs = useAsync(() => api.runs.list(), [])
  const evaluations = useAsync(() => api.gateEvaluations.list(), [])
  const [runId, setRunId] = useState('')
  const [busy, setBusy] = useState<string | null>(null)
  const [error, setError] = useState<string | null>(null)

  const effectiveRunId = runId || String(runs.data?.[0]?.id ?? '')
  const selectedRun = useMemo(
    () => (runs.data ?? []).find((run) => run.id === Number(effectiveRunId)) ?? null,
    [runs.data, effectiveRunId],
  )

  async function handleDownload(format: string) {
    if (!effectiveRunId) return
    setError(null)
    setBusy(format)
    try {
      const blob = await api.runs.exportBlob(Number(effectiveRunId), format)
      const name = exportFileName(`run-${effectiveRunId}`, format)
      downloadBlob(blob, { fileName: name })
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : 'The report could not be generated.')
    } finally {
      setBusy(null)
    }
  }

  return (
    <>
      <PageHeader
        title="Reports"
        description="Download a run as a shareable report, or review the gate evaluations that were produced from past runs."
      />

      <Card title="Download a run report" subtitle="Reports are generated by the backend from the frozen run artefacts.">
        <Field label="Evaluation run" htmlFor="report-run">
          <select id="report-run" value={effectiveRunId} onChange={(event) => setRunId(event.target.value)}>
            {(runs.data ?? []).map((run) => (
              <option key={run.id} value={run.id}>
                #{run.id} · {run.app_name} {run.app_version} · {run.dataset_name}
              </option>
            ))}
          </select>
        </Field>

        {selectedRun && (
          <p className="text-small text-muted">
            {selectedRun.app_name} {selectedRun.app_version} · {selectedRun.dataset_name} · {selectedRun.mode} ·{' '}
            {formatDateTime(selectedRun.created_at)}
          </p>
        )}

        <div className="row">
          {FORMATS.map((entry) => (
            <button
              key={entry.format}
              type="button"
              className="btn btn-primary"
              onClick={() => handleDownload(entry.format)}
              disabled={busy !== null || !effectiveRunId}
            >
              {busy === entry.format ? 'Generating…' : `Download ${entry.label}`}
            </button>
          ))}
        </div>

        {error && <Notice tone="danger">{error}</Notice>}
        <Notice tone="info">
          The CI summary is a machine-readable JSON document with the verdict and the failing checks — it is the format to
          use in a pipeline.
        </Notice>
      </Card>

      <Card title="Past gate evaluations" subtitle="Every evaluation that was produced from a run.">
        {evaluations.loading ? (
          <Skeleton rows={5} />
        ) : evaluations.error ? (
          <ErrorState message={evaluations.error} onRetry={evaluations.reload} />
        ) : (evaluations.data ?? []).length === 0 ? (
          <EmptyState
            title="No reports yet"
            message="Evaluate a candidate run against a gate policy to produce a report."
          />
        ) : (
          <div className="table-wrap">
            <table className="data">
              <caption className="sr-only">Past gate evaluations</caption>
              <thead>
                <tr>
                  <th scope="col">Evaluation</th>
                  <th scope="col">Verdict</th>
                  <th scope="col">Candidate</th>
                  <th scope="col">Baseline</th>
                  <th scope="col">Summary</th>
                  <th scope="col">Created</th>
                  <th scope="col">Report</th>
                </tr>
              </thead>
              <tbody>
                {(evaluations.data ?? []).map((evaluation) => (
                  <tr
                    key={evaluation.id}
                    className={
                      evaluation.verdict === 'FAIL' ? 'row-danger' : evaluation.verdict === 'INCONCLUSIVE' ? 'row-warning' : ''
                    }
                  >
                    <td className="num">#{evaluation.id}</td>
                    <td>
                      <VerdictBadge verdict={evaluation.verdict} />
                    </td>
                    <td>
                      <RunLink id={evaluation.candidate_run_id} />
                    </td>
                    <td>{evaluation.baseline_run_id ? <RunLink id={evaluation.baseline_run_id} /> : '—'}</td>
                    <td className="text-small">{evaluation.summary}</td>
                    <td className="text-small">{formatDateTime(evaluation.created_at)}</td>
                    <td>
                      <button
                        type="button"
                        className="btn btn-secondary btn-sm"
                        onClick={() => {
                          setRunId(String(evaluation.candidate_run_id))
                          window.scrollTo({ top: 0, behavior: 'smooth' })
                        }}
                        aria-label={`Open the report for evaluation ${evaluation.id}`}
                      >
                        Open report
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>
    </>
  )
}
